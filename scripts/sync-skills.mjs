#!/usr/bin/env node
/**
 * dsh-obsidian-skills — regenerate ./skills from the upstream repository.
 *
 * Usage:
 *   node scripts/sync-skills.mjs              # write
 *   node scripts/sync-skills.mjs --dry-run    # show what would change
 *   node scripts/sync-skills.mjs --check      # exit 1 when stale
 *
 * Environment:
 *   OBSIDIAN_SKILLS_SRC  local clone of kepano/obsidian-skills
 *                        (default /tmp/obsidian-skills-src)
 *   OBSIDIAN_SKILLS_REF  git ref to fetch when the clone is absent
 *                        (default main)
 *
 * Upstream: https://github.com/kepano/obsidian-skills (MIT, Steph Ango).
 * This script copies skills/<name>/**? verbatim. It never edits upstream text.
 */

import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS_DIR = join(ROOT, 'skills');
const MANIFEST = join(ROOT, 'skills.manifest.json');

const UPSTREAM = 'https://github.com/kepano/obsidian-skills';
const SRC = process.env.OBSIDIAN_SKILLS_SRC || '/tmp/obsidian-skills-src';
const REF = process.env.OBSIDIAN_SKILLS_REF || 'main';

const argv = new Set(process.argv.slice(2));
const DRY_RUN = argv.has('--dry-run');
const CHECK = argv.has('--check');

/** Recursively list files under dir, relative to it, sorted. */
function walk(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, base));
    else out.push(full.slice(base.length + 1));
  }
  return out.sort();
}

/** Ensure the upstream clone exists; fetch it when missing. */
function ensureSource() {
  if (existsSync(join(SRC, 'skills'))) return SRC;
  if (DRY_RUN || CHECK) return null;
  console.error(`upstream clone missing at ${SRC}; cloning ${UPSTREAM} (${REF})...`);
  mkdirSync(dirname(SRC), { recursive: true });
  execFileSync('git', ['clone', '--depth', '1', '--branch', REF, UPSTREAM, SRC], {
    stdio: 'inherit',
  });
  return SRC;
}

function manifestFor(names, fileCounts) {
  return JSON.stringify(
    {
      source: 'generated by scripts/sync-skills.mjs',
      upstream: UPSTREAM,
      skillCount: names.length,
      fileCount: Object.values(fileCounts).reduce((a, b) => a + b, 0),
      skills: names.map((n) => ({ name: n, files: fileCounts[n] })),
    },
    null,
    2,
  ) + '\n';
}

function main() {
  const src = ensureSource();
  if (src === null) {
    console.error(`missing source: ${SRC}/skills`);
    process.exit(1);
  }

  const srcSkills = join(src, 'skills');
  const names = readdirSync(srcSkills, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .sort();

  const fileCounts = {};
  const stale = [];

  // 1. Per-skill trees.
  for (const name of names) {
    const from = join(srcSkills, name);
    const to = join(SKILLS_DIR, name);
    const files = walk(from);
    fileCounts[name] = files.length;

    for (const rel of files) {
      const content = readFileSync(join(from, rel));
      const target = join(to, rel);
      const current = existsSync(target) ? readFileSync(target) : null;
      const same = current !== null && Buffer.compare(current, content) === 0;
      if (same) continue;
      stale.push(target);
      if (!DRY_RUN && !CHECK) {
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, content);
      }
    }
  }

  // 2. Remove skill directories upstream no longer ships.
  const keep = new Set(names);
  if (existsSync(SKILLS_DIR)) {
    for (const entry of readdirSync(SKILLS_DIR, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
      if (keep.has(entry.name)) continue;
      const gone = join(SKILLS_DIR, entry.name);
      stale.push(gone);
      if (!DRY_RUN && !CHECK) rmSync(gone, { recursive: true, force: true });
    }
  }

  // 3. Manifest.
  const manifest = manifestFor(names, fileCounts);
  const currentManifest = existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : null;
  if (currentManifest !== manifest) {
    stale.push(MANIFEST);
    if (!DRY_RUN && !CHECK) writeFileSync(MANIFEST, manifest);
  }

  if (DRY_RUN) {
    console.log(stale.length === 0 ? 'up to date' : `would update ${stale.length} path(s):`);
    for (const p of stale) console.log(`  ${p}`);
    return;
  }

  if (CHECK) {
    if (stale.length === 0) {
      console.log('up to date');
      return;
    }
    console.error(`stale: ${stale.length} path(s) differ from ${UPSTREAM}:`);
    for (const p of stale) console.error(`  ${p}`);
    process.exit(1);
  }

  console.log(stale.length === 0 ? 'up to date' : `wrote ${stale.length} path(s)`);
  console.log(`  ${names.length} skill(s): ${names.join(', ')}`);
}

main();
